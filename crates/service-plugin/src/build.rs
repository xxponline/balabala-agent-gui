//! 构建指纹嵌入（task 3.2，design D8/D12 路线甲）。
//!
//! 插件的 `build.rs` 只需：
//!
//! ```ignore
//! fn main() {
//!     service_plugin::build::emit_fingerprint();
//! }
//! ```
//!
//! 插件 `lib.rs` 引入生成的导出符号：
//!
//! ```ignore
//! include!(concat!(env!("OUT_DIR"), "/service_fingerprint.rs"));
//! ```
//!
//! 与宿主（`service-manager/build.rs`）用**同一份算法**
//! （`service_core::fingerprint`），Loader 装载前比对，不匹配显式拒载。

use service_core::fingerprint;
use std::path::{Path, PathBuf};

/// 生成文件名（插件 lib.rs `include!` 相对 `$OUT_DIR`）。
pub const FINGERPRINT_RS: &str = "service_fingerprint.rs";

/// 供插件 build.rs 调用：计算插件指纹、写 `$OUT_DIR/service_fingerprint.rs`
/// （含 `#[unsafe(no_mangle)] SERVICE_CONTRACT_FINGERPRINT` 导出符号）、打印
/// `rerun-if-changed`。返回计算出的指纹（方便构建日志）。
pub fn emit_fingerprint() -> String {
    let manifest = PathBuf::from(
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR available to build.rs"),
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR available to build.rs"));
    let contract_src = fingerprint::contract_src_from(&manifest);
    if let Some(src) = &contract_src {
        println!("cargo:rerun-if-changed={}", src.display());
    }
    let version = fingerprint::rustc_version().expect("rustc --version");
    write_fingerprint(&version, contract_src.as_deref(), &out)
        .expect("write service_fingerprint.rs")
}

/// 实际写文件（独立出来便于单测；宿主/插件逻辑一致的保证点）。
pub fn write_fingerprint(
    rustc_version: &str,
    contract_src: Option<&Path>,
    out_dir: &Path,
) -> Result<String, std::io::Error> {
    let fp = fingerprint::compute(rustc_version, contract_src)?;
    let contents = format!(
        "// @generated by service_plugin::build::emit_fingerprint — do not edit.\n\
         // 构建指纹 (D8): Loader 装载前与宿主比对, 不匹配显式拒载。\n\
         #[unsafe(no_mangle)]\n\
         pub static SERVICE_CONTRACT_FINGERPRINT: &[u8] = b\"{fp}\";\n"
    );
    std::fs::write(out_dir.join(FINGERPRINT_RS), contents)?;
    Ok(fp)
}

#[cfg(test)]
mod tests {
    use super::*;
    use service_core::FINGERPRINT_SYMBOL;

    #[test]
    fn emit_writes_exportable_static_with_fp_prefix() {
        let out = std::env::temp_dir().join(format!("smf-plugin-emit-{}", std::process::id()));
        std::fs::create_dir_all(&out).unwrap();
        let fp = write_fingerprint("rustc 1.85.0 (test)", None, &out).unwrap();

        let generated = std::fs::read_to_string(out.join(FINGERPRINT_RS)).unwrap();
        assert!(generated.contains("#[unsafe(no_mangle)]"), "须是导出符号");
        assert!(
            generated.contains(std::str::from_utf8(FINGERPRINT_SYMBOL).unwrap()),
            "符号名与 service_core::FINGERPRINT_SYMBOL 一致"
        );
        assert!(generated.contains(&fp), "嵌入计算出的指纹");
        assert!(fp.starts_with(fingerprint::FINGERPRINT_PREFIX));
        std::fs::remove_dir_all(&out).ok();
    }

    #[test]
    fn emitted_fingerprint_format_matches_host_verifier() {
        // 插件侧生成的文件可被宿主 verify() 接受的格式 (同算法)
        let out = std::env::temp_dir().join(format!("smf-plugin-emit2-{}", std::process::id()));
        std::fs::create_dir_all(&out).unwrap();
        let plugin_fp = write_fingerprint("rustc 9.9.9", None, &out).unwrap();
        let host_fp = fingerprint::compute("rustc 9.9.9", None).unwrap();
        fingerprint::verify(&plugin_fp, &host_fp).expect("同输入同指纹");
        std::fs::remove_dir_all(&out).ok();
    }
}
